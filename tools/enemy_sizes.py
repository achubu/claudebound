# Round 351 (owner: "standardize enemy size across all worlds, similar to what we see in Neon Aftermath").
# Every creature sheet is drawn in the same box, but the painted creature fills it by very different amounts (a moth or
# a scarab is far smaller than a sentinel), and the Sky Isles and Solaris creatures are the smallest on average.
# This measures each four-frame sheet's painted size (the square root of the share of each frame its opaque pixels cover,
# averaged over the four frames: a bounding box flatters thin, winged creatures) and writes assets/enemy-sizes.css, which scales each creature on the map toward
# the Neon Aftermath average (TARGET), within CLAMP. Battle portraits are not touched.
# Run after adding or re-cutting creature sheets:  python3 tools/enemy_sizes.py
import glob, math, os
import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TARGET = 0.55          # the median Neon Aftermath creature (they range 0.48-0.69)
CLAMP = (0.85, 1.45)   # small creatures grow up to 45%; big ones shrink at most 15%

def painted_size(path):
    im = Image.open(path)
    W, H = im.size
    if abs(W / 4 - H * 0.75) > H * 0.05:
        return None  # not a four-frame 3:4 strip
    a = np.array(im.convert('RGBA'))[..., 3] > 100
    fw = W // 4
    return math.sqrt(np.mean([a[:, i * fw:(i + 1) * fw].mean() for i in range(4)]))

rules = []
for f in sorted(glob.glob(os.path.join(ROOT, 'assets/monsters/**/*.png'), recursive=True)):
    rel = os.path.relpath(f, os.path.join(ROOT, 'assets/monsters')).replace(os.sep, '/')
    if rel.startswith('src/') or '/src/' in rel or 'preview' in rel:
        continue
    s = painted_size(f)
    if s is None:
        continue
    fit = round(min(CLAMP[1], max(CLAMP[0], TARGET / s)), 3)
    rules.append((rel, s, fit))

out = ['/* Generated by tools/enemy_sizes.py (Round 351): each creature sheet scaled on the map toward one painted size. */']
for rel, s, fit in rules:
    if abs(fit - 1) < 0.01:
        continue
    out.append('#world .enemy-node .wildlife-sprite[style*="/%s"]{--enemy-fit:%s} /* painted %.3f */' % (rel, fit, s))
out.append('#world .enemy-node > .monster-sprite.wildlife-sprite{scale:calc(.88 * var(--enemy-fit,1))!important;transform-origin:50% 100%}')
out.append('#world .enemy-node .pair-ghost .monster-sprite.wildlife-sprite{scale:var(--enemy-fit,1);transform-origin:50% 100%}')
open(os.path.join(ROOT, 'assets/enemy-sizes.css'), 'w').write('\n'.join(out) + '\n')
print(len(rules), 'sheets;', sum(1 for r in rules if abs(r[2] - 1) >= .01), 'resized')
for rel, s, fit in sorted(rules, key=lambda r: r[2]):
    print('%-40s painted %.3f  x%.2f' % (rel, s, fit))
