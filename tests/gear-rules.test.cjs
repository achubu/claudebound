'use strict';
// Round 284: every gear piece also changes a rule while worn.
process.env.HARNESS_ONLY = '1';
const assert = require('assert');
const { run } = require('./expansion.test.cjs');
const r = JSON.parse(run(`(() => { const o = {};
  const fight = (...gear) => { newGame(); configureRegion('city'); state.relics = Object.keys(GEAR); ensureGear(); for (const g of gear) equipGear(GEAR[g].slot, g);
    state.hp = state.maxHp = 100; state.room = '1,5'; const s = roomSpawns('1,5').find(x => !x.boss); startBattle(s.uid); const b = state.battle;
    b.enemy = { ...b.enemy, hp: 300, maxHp: 300, armor: 0, guard: 0, attack: 10, element: null }; b.hand = []; b.draw = Array.from({ length: 20 }, () => make('guard')); b.discard = []; b.energy = 9; b.turn = 1; return b; };
  const play = (b, id) => { b.hand.push(make(id)); playCard(b.hand.length - 1); };
  o.ids = Object.keys(GEAR).filter(id => !GEAR_RULES[id]);
  let b = fight('ember'); play(b, 'strike'); const burn1 = b.burn; play(b, 'strike'); o.kindle = { burn: burn1, once: (b.logs.join(' ').match(/Kindle/g) || []).length };
  b = fight('scarabBelt'); play(b, 'mend'); play(b, 'mend'); o.scarab = b.hand.length;
  b = fight('galeweavePants'); for (let i = 0; i < 3; i++) play(b, 'guard'); const blk = b.block; play(b, 'guard'); o.gale = b.block - blk - statBeforeTwists(make('guard')).block;
  b = fight('thornhideGloves'); state.hp = 50; for (let i = 0; i < 6; i++) play(b, 'strike'); o.thirst = state.hp - 50;
  b = fight('mossweavePants'); state.hp = 50; b.block = 999; endTurn(); o.moss = { hp: state.hp, turn: b.turn };
  b = fight('cloudstepBoots'); const hp0 = state.hp; endTurn(); o.cloud = hp0 - state.hp; endTurn(); const hp1 = state.hp; endTurn(); o.cloud2 = hp1 - state.hp;
  b = fight('hourglassBelt'); b.block = 999; b.energy = 2; endTurn(); o.hour = b.energy - maxEnergy();
  b = fight('timewornShirt'); state.hp = 60; b.enemy.attack = 200; b.block = 0; endTurn(); o.second = { phase: b.phase, hp: state.hp }; endTurn(); state.hp = 60; b.block = 0; b.hand = []; endTurn(); o.second2 = state.battle.phase;
  b = fight('timewornShirt'); state.hp = 1; b.block = 0; endTurn(); o.chip = b.phase;
  b = fight('boots'); b.block = 50; const e0 = b.enemy.hp; endTurn(); o.briar = e0 - b.enemy.hp;
  b = fight('stormglassBelt'); for (let i = 0; i < 6; i++) play(b, 'guard'); const sb = b.block; play(b, 'guard'); o.storm = b.block - sb;
  b = fight(); play(b, 'strike'); o.none = b.logs.filter(l => /Kindle|Thirst/.test(l)).length;
  o.text = gearText('ember');
  return JSON.stringify(o); })()`));
assert.deepStrictEqual(r.ids, [], 'every piece has a rule');
assert(r.kindle.burn >= 2 && r.kindle.once === 1, 'Kindle burns on the first attack only');
assert.strictEqual(r.scarab, 1, 'Scarab Swarm draws a card on the first 0-cost card');
assert.strictEqual(r.gale, 4, 'Gale Rhythm: the 4th card gets +4 Block');
assert.strictEqual(r.thirst, 4, 'Thirst heals 1 per attack, up to 4 a fight');
assert(r.moss.turn === 2 && r.moss.hp === 51, 'Moss Mend heals 1 at the start of your turn');
assert(r.cloud > 0 && r.cloud < r.cloud2, 'Cloudstep halves only the first hit');
assert.strictEqual(r.hour, 1, 'Saved Moment carries over 1 energy');
assert(r.second.phase === 'fight' && r.second.hp === 1 && r.second2 === 'lost', 'Second Chance saves you once'); assert.strictEqual(r.chip, 'lost', 'but not from low health');
assert.strictEqual(r.briar, 3, 'Briar Guard hits back when Block stops the hit');
assert.strictEqual(r.storm, 11, 'Stormglass: the 7th card gains 6 more Block'); assert.strictEqual(r.none, 0, 'no rules without gear');
assert(/Kindle/.test(r.text), 'the rule shows with the boost');
console.log('gear-rules ok');
